export function money(n: number, lang: Lang) {
  return `${Math.round(n).toLocaleString(lang === "ar" ? "ar-EG-u-nu-latn" : "en-US")} ${dict[lang].currency}`;
}

export function num(n: number, lang: Lang) {
  return n.toLocaleString(lang === "ar" ? "ar-EG-u-nu-latn" : "en-US");
}

export function fmtDate(iso: string, lang: Lang) {
  return new Date(iso + "T00:00:00Z").toLocaleDateString(lang === "ar" ? "ar-EG-u-nu-latn" : "en-GB", {
    day: "numeric",
    month: "short",
    timeZone: "UTC",
  });
}
